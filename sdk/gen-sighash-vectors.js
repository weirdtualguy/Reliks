'use strict';
// One-off generator: records what the sighash in reliks-lib.js returns for 60 pseudo-random transactions.
// It evaluates reliks-lib.js only up to the line that loads config, so no key, wallet check or secrets.env is ever read.
// Usage: PC_NET=testnet node sdk/gen-sighash-vectors.js
process.env.PC_NET = process.env.PC_NET || 'testnet';
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
const src = fs.readFileSync(path.join(root, 'reliks-lib.js'), 'utf8');
const cut = src.indexOf("const PRIV = require('./config').PRIV;");
if (cut < 0) throw new Error("anchor not found in reliks-lib.js: const PRIV = require('./config').PRIV;");
const head = src.slice(0, cut);
if (head.indexOf("require('./config')") >= 0) throw new Error('config is required before the cut; cannot extract safely');
const mod = { exports: {} };
const req = (m) => (m.charAt(0) === '.' ? require(path.join(root, m)) : require(m));
const V = new Function('require', 'module', 'exports', '__dirname', head + '\nreturn { sighash: typeof sighash === "function" ? sighash : null };')(req, mod, mod.exports, root);
if (!V.sighash) throw new Error('sighash not defined in the extracted part of reliks-lib.js');
let s = 0x2545F491;
const rnd = () => { s ^= s << 13; s >>>= 0; s ^= s >>> 17; s >>>= 0; s ^= s << 5; s >>>= 0; return s; };
const hex = (n) => Array.from({ length: n }, () => (rnd() & 255).toString(16).padStart(2, '0')).join('');
const big = () => (BigInt(rnd()) * BigInt(rnd()) + BigInt(rnd())) % (1n << 62n);
const spk = () => (rnd() % 2 ? 'aa20' + hex(32) + '87' : '20' + hex(32) + 'ac');
const cases = [];
for (let k = 0; k < 60; k++) {
  const nIn = 1 + rnd() % 3, nOut = 1 + rnd() % 5;
  const inputs = Array.from({ length: nIn }, () => ({ txId: hex(32), index: rnd() % 5, sequence: rnd() % 2 ? '0' : String(rnd()), spk: spk(), amount: String(big()) }));
  const outputs = Array.from({ length: nOut }, () => { const o = { amount: String(big()), scriptPublicKey: spk() }; if (rnd() % 2) o.covenant = { authorizingInput: rnd() % nIn, covenantId: hex(32) }; return o; });
  const idx = rnd() % nIn;
  const expected = V.sighash(inputs.map((i) => ({ txId: i.txId, index: i.index, sequence: BigInt(i.sequence), spk: i.spk, amount: BigInt(i.amount) })), outputs.map((o) => ({ amount: BigInt(o.amount), scriptPublicKey: o.scriptPublicKey, covenant: o.covenant })), idx).toString('hex');
  cases.push({ inputs, outputs, idx, expected });
}
fs.writeFileSync(path.join(__dirname, 'sighash-vectors.json'), JSON.stringify({ note: 'generated by sdk/gen-sighash-vectors.js from the sighash in reliks-lib.js; do not edit', cases }, null, 1) + '\n');
console.log('wrote', cases.length, 'vectors');
