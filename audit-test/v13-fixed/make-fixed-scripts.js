const fs = require('fs');
const die = m => { console.error('PATCH FAIL: ' + m); process.exit(1); };
const rep = (s, a, b, tag) => { if (s.split(a).length !== 2) die(tag + ': need exactly one match for: ' + a.slice(0, 70)); return s.replace(a, () => b); };
const FX = 'audit-test/v13-fixed';
function patch(src, dst, edits) {
  let s = fs.readFileSync(src, 'utf8');
  s = s.replace(/require\((['"])\.\//g, 'require($1../');
  s = s.split('data/factory-ledger-v12.json').join(FX + '/ledger.json');
  s = s.split('data/edition-abi-v12.json').join(FX + '/out/edition.json');
  s = s.split('data/factory-abi-v12.json').join(FX + '/out/factory.json');
  s = s.split('data/factory-args-v12.json').join(FX + '/factory-args.json');
  s = s.split('data/escrow-abi-v5.json').join(FX + '/out/escrow.json');
  s = s.split('data/escrow-ledger-v5.json').join(FX + '/escrow-ledger.json');
  s = s.split('waitForConfirmation(txId)').join('waitForConfirmation(txId, 600000)');
  // depth fix: these scripts live 2 levels deep, not 1
  s = s.split("require('../lib/reliks-lib.js')").join("require('../../lib/reliks-lib.js')");
  s = s.split("require('../lib/reliks-engine-mainnet.js')").join("require('../../lib/reliks-engine-mainnet.js')");
  s = s.split('"../lib/reliks-engine-mainnet.js"').join('"../../lib/reliks-engine-mainnet.js"');
  for (const [a, b] of edits) s = rep(s, a, b, src);
  fs.writeFileSync(dst, '// GENERATED by make-fixed-scripts.js, testnet only. Do not edit.\nif ((process.env.PC_NET || "testnet") !== "testnet") { console.error("fixed scripts are testnet-only"); process.exit(1); }\n' + s);
}
